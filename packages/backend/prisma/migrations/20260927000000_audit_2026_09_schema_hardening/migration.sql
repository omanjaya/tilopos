DECLARE n integer;
BEGIN
  SELECT count(*) INTO n FROM (
    SELECT transaction_id FROM credit_sales GROUP BY transaction_id HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE EXCEPTION 'audit_2026_09: % transaction(s) have more than one credit_sales row; resolve duplicates before creating uq_credit_sale_transaction', n;
  END IF;

  SELECT count(*) INTO n FROM (
    SELECT 1 FROM online_orders GROUP BY outlet_id, platform, platform_order_id HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE EXCEPTION 'audit_2026_09: % duplicate (outlet_id, platform, platform_order_id) groups in online_orders; resolve before creating uq_online_order_platform', n;
  END IF;

  SELECT count(*) INTO n FROM (
    SELECT 1 FROM payment_settlements GROUP BY outlet_id, settlement_date, payment_method HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE EXCEPTION 'audit_2026_09: % duplicate (outlet_id, settlement_date, payment_method) groups in payment_settlements (double settlement); resolve before creating uq_settlement_outlet_date_method', n;
  END IF;

  SELECT count(*) INTO n FROM (
    SELECT 1 FROM stock_levels WHERE variant_id IS NULL GROUP BY outlet_id, product_id HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE EXCEPTION 'audit_2026_09: % duplicate non-variant stock_levels rows per (outlet_id, product_id); merge quantities before creating uq_stock_outlet_product_no_variant', n;
  END IF;

  SELECT count(*) INTO n FROM (
    SELECT 1 FROM shifts WHERE status = 'open' GROUP BY employee_id HAVING count(*) > 1) d;
  IF n > 0 THEN
    RAISE EXCEPTION 'audit_2026_09: % employee(s) have more than one open shift; close the extra shifts before creating uq_shift_open_per_employee', n;
  END IF;
END $$;

