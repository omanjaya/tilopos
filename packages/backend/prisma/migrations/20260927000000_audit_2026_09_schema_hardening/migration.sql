-- StockLevel: uq_stock_outlet_product_variant does not cover variant_id IS NULL
-- (NULLs are distinct), so enforce one non-variant row per outlet/product.
CREATE UNIQUE INDEX "uq_stock_outlet_product_no_variant"
  ON "stock_levels"("outlet_id", "product_id") WHERE "variant_id" IS NULL;

-- Shift: at most one open shift per employee (closes the check-then-create race).
CREATE UNIQUE INDEX "uq_shift_open_per_employee"
  ON "shifts"("employee_id") WHERE "status" = 'open';

-- NotificationSetting: outlet_id/employee_id are nullable; make NULLs compare equal
-- so business-level settings are unique too. Duplicate config rows are removed
-- first (the most recently updated row of each group is kept).
DELETE FROM "notification_settings" ns
 USING (
   SELECT "id", row_number() OVER (
            PARTITION BY "business_id", "outlet_id", "employee_id", "notification_type", "channel"
            ORDER BY "updated_at" DESC, "created_at" DESC, "id") AS rn
     FROM "notification_settings") d
 WHERE ns."id" = d."id" AND d.rn > 1;
DROP INDEX "uq_notification_setting";
CREATE UNIQUE INDEX "uq_notification_setting"
  ON "notification_settings"("business_id", "outlet_id", "employee_id", "notification_type", "channel")
  NULLS NOT DISTINCT;

-- ---------------------------------------------------------------------------
-- 4. Backfill refund_of_id from the legacy "Refund for: <receipt>" note
--    written by ProcessRefundUseCase (same outlet, exact receipt match).
-- ---------------------------------------------------------------------------
UPDATE "transactions" r
   SET "refund_of_id" = o."id"
  FROM "transactions" o
 WHERE r."transaction_type" = 'refund'
   AND r."refund_of_id" IS NULL
   AND r."notes" IS NOT NULL
   AND o."outlet_id" = r."outlet_id"
   AND o."transaction_type" = 'sale'
   AND split_part(r."notes", ' - ', 1) = 'Refund for: ' || o."receipt_number";
